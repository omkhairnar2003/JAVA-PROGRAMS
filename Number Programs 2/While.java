////prg to print 1 to 100 numbers using while loop

class While 
{
	public static void main(String[] args) 
	{
		int i;
        System.out.println("Numbers upto 100 are");
        i = 1;
        while (i <= 100) 
        {
            System.out.print(i + " ");
            i++;
        }
    }
}
