class NarrowingDouble 
{
	public static void main(String[] args) 
	{
		System.out.println("double d = "+200.00);
		System.out.println("float f = "+(float)200.00);
		System.out.println("long l = "+(long)200.00);
		System.out.println("int i = "+(int)200.00);
		System.out.println("short s = "+(short)200.00);
		System.out.println("char c = "+(char)200.00);
		System.out.println("byte b = "+(byte)200.00);
	}
}