class NarrowingFloat 
{
	public static void main(String[] args) 
	{
		System.out.println("float f = "+(float)2000.00f);
		System.out.println("long l = "+(long)2000.00f);
		System.out.println("int i = "+(int)2000.00f);
		System.out.println("short s = "+(short)2000.00f);
		System.out.println("char c = "+(char)2000.00f);
		System.out.println("byte b = "+(byte)2000.00f);
	}
}