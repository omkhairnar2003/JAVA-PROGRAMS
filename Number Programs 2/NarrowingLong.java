class NarrowingLong 
{
	public static void main(String[] args) 
	{
		System.out.println("long l = "+(long)100000l);
		System.out.println("int i = "+(int)100000l);
		System.out.println("short s = "+(short)100000l);
		System.out.println("char c = "+(char)100000l);
		System.out.println("byte b = "+(byte)100000l);
	}
}