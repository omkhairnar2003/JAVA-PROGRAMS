// Area of rectangle
class AreaRectangle
{
	public static void main(String[] args) 
	{
	 float width =4.5f;
	 float height=7.9f;
	 System.out.println("width of rectangle :"+width);
	 System.out.println("height of rectangle :"+height);
	 float area=width*height;
	 System.out.println("area of rectangle :"+area);
    }
}