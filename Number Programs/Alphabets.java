//prg to print A to Z alphabets using while loop

class Alphabets
 {
    public static void main(String[] args) 
    {
        char i;
        System.out.println("The Alphabets from A to Z are: ");
        i = 'A';
        while (i <= 'Z') 
        {
            System.out.print(i + " ");
            i++;
        }
    }
}

